export type Key = keyof typeof copy;
export const translate = (locale: Locale, key: Key): string =>
  copy[key][locale === 'vi-VN' ? 0 : 1];
export const currency = (value: number, locale: Locale = 'vi-VN') =>
  new Intl.NumberFormat(locale, {
    style: 'currency',
    currency: 'VND',
    maximumFractionDigits: 0,
  }).format(value);
export const numeric = (value: number, locale: Locale) =>
  new Intl.NumberFormat(locale, { maximumFractionDigits: 2 }).format(value);
export const percent = (value: number, locale: Locale) =>
  new Intl.NumberFormat(locale, { style: 'percent', maximumFractionDigits: 2 }).format(value / 100);
export const date = (value: string | Date, locale: Locale) =>
  new Intl.DateTimeFormat(locale, {
    timeZone: 'Asia/Ho_Chi_Minh',
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  }).format(new Date(value));
